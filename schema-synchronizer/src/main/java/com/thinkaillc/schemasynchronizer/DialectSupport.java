package com.thinkaillc.schemasynchronizer;

import java.sql.Connection;
import java.sql.SQLException;
import java.sql.Statement;
import java.sql.Types;
import java.util.Locale;
import java.util.Objects;

/** Dialect-specific locking and history DDL helpers. */
final class DialectSupport {
    /** MySQL GET_LOCK resource names truncate at 64 characters. */
    static final int MYSQL_LOCK_NAME_MAX = 64;

    private DialectSupport() {
    }

    static String createHistoryDdl(DatabaseDialect dialect, String qualifiedHistory) {
        return switch (dialect) {
            case POSTGRESQL -> "CREATE TABLE IF NOT EXISTS " + qualifiedHistory + " ("
                    + "installed_rank BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "
                    + "change_id VARCHAR(200) NOT NULL UNIQUE, "
                    + "checksum CHAR(64) NOT NULL, "
                    + "description VARCHAR(500), "
                    + "applied_by VARCHAR(200), "
                    + "applied_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP, "
                    + "execution_ms BIGINT NOT NULL)";
            case MARIADB, MYSQL -> "CREATE TABLE IF NOT EXISTS " + qualifiedHistory + " ("
                    + "installed_rank BIGINT AUTO_INCREMENT PRIMARY KEY, "
                    + "change_id VARCHAR(200) NOT NULL UNIQUE, "
                    + "checksum CHAR(64) NOT NULL, "
                    + "description VARCHAR(500), "
                    + "applied_by VARCHAR(200), "
                    + "applied_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP, "
                    + "execution_ms BIGINT NOT NULL)";
            case SQLSERVER -> "IF OBJECT_ID(N'" + escapeSqlServerLiteral(qualifiedHistory) + "', N'U') IS NULL "
                    + "CREATE TABLE " + qualifiedHistory + " ("
                    + "installed_rank BIGINT IDENTITY(1,1) NOT NULL PRIMARY KEY, "
                    + "change_id VARCHAR(200) NOT NULL UNIQUE, "
                    + "checksum CHAR(64) NOT NULL, "
                    + "description VARCHAR(500) NULL, "
                    + "applied_by VARCHAR(200) NULL, "
                    + "applied_at DATETIMEOFFSET NOT NULL DEFAULT SYSDATETIMEOFFSET(), "
                    + "execution_ms BIGINT NOT NULL)";
            case ORACLE -> "BEGIN EXECUTE IMMEDIATE 'CREATE TABLE " + qualifiedHistory + " ("
                    + "installed_rank NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "
                    + "change_id VARCHAR2(200) NOT NULL UNIQUE, "
                    + "checksum CHAR(64) NOT NULL, "
                    + "description VARCHAR2(500), "
                    + "applied_by VARCHAR2(200), "
                    + "applied_at TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL, "
                    + "execution_ms NUMBER NOT NULL)'; "
                    + "EXCEPTION WHEN OTHERS THEN IF SQLCODE != -955 THEN RAISE; END IF; END;";
        };
    }

    /** Adds {@code applied_by} to an existing history table created before 1.4.0. */
    static String addAppliedByColumnDdl(DatabaseDialect dialect, String qualifiedHistory) {
        return switch (dialect) {
            case POSTGRESQL -> "ALTER TABLE " + qualifiedHistory
                    + " ADD COLUMN IF NOT EXISTS applied_by VARCHAR(200)";
            // MariaDB accepts IF NOT EXISTS; MySQL 8/9 does not — catch duplicate column instead.
            case MARIADB -> "ALTER TABLE " + qualifiedHistory
                    + " ADD COLUMN IF NOT EXISTS applied_by VARCHAR(200)";
            case MYSQL -> "ALTER TABLE " + qualifiedHistory
                    + " ADD COLUMN applied_by VARCHAR(200)";
            case SQLSERVER -> "IF COL_LENGTH(N'" + escapeSqlServerLiteral(qualifiedHistory)
                    + "', N'applied_by') IS NULL ALTER TABLE " + qualifiedHistory
                    + " ADD applied_by VARCHAR(200) NULL";
            case ORACLE -> "BEGIN EXECUTE IMMEDIATE 'ALTER TABLE " + qualifiedHistory
                    + " ADD applied_by VARCHAR2(200)'; "
                    + "EXCEPTION WHEN OTHERS THEN IF SQLCODE != -1430 THEN RAISE; END IF; END;";
        };
    }

    /**
     * True when {@code error} is a duplicate-column failure for the dialect
     * (idempotent history {@code applied_by} migration).
     */
    static boolean isDuplicateColumn(DatabaseDialect dialect, SQLException error) {
        if (error == null) {
            return false;
        }
        for (Throwable current = error; current != null; current = nextSqlFailure(current)) {
            if (!(current instanceof SQLException sql)) {
                continue;
            }
            String state = sql.getSQLState();
            int code = sql.getErrorCode();
            switch (dialect) {
                case MYSQL, MARIADB -> {
                    // 1060 = ER_DUP_FIELDNAME
                    if (code == 1060 || "42S21".equals(state)) {
                        return true;
                    }
                }
                case POSTGRESQL -> {
                    // 42701 = duplicate_column
                    if ("42701".equals(state)) {
                        return true;
                    }
                }
                case SQLSERVER -> {
                    // 2705 = Column names in each table must be unique
                    if (code == 2705) {
                        return true;
                    }
                }
                case ORACLE -> {
                    // ORA-01430 = column being added already exists
                    if (code == 1430) {
                        return true;
                    }
                }
            }
        }
        return false;
    }

    /** Prefer {@link SQLException#getNextException()}, then {@link Throwable#getCause()}. */
    private static Throwable nextSqlFailure(Throwable current) {
        if (current instanceof SQLException sql && sql.getNextException() != null) {
            return sql.getNextException();
        }
        return current.getCause();
    }

    /**
     * Acquires an exclusive synchronization lock. Returns a token for {@link #releaseLock}
     * (may be {@code null} when the dialect uses transaction-scoped locks).
     */
    static String acquireLock(Connection conn, DatabaseDialect dialect, String namespace, long advisoryLockId)
            throws SQLException {
        return switch (dialect) {
            case POSTGRESQL -> {
                // Two-key lock mixes schema namespace with the configured id so products
                // sharing one Postgres cluster do not serialize on the default id alone.
                // Also acquire the 1.3.0 single-key form so rolling upgrades still exclude
                // peers still on the old lock space (the two spaces are independent).
                // pg_try_* with a 30s deadline matches MySQL/SQL Server lock timeouts
                // (pg_advisory_xact_lock waits forever).
                int key1 = namespaceLockKey(namespace);
                int key2 = Math.floorMod(Long.hashCode(advisoryLockId), Integer.MAX_VALUE);
                acquirePostgresLocks(conn, key1, key2, advisoryLockId);
                yield null;
            }
            case MARIADB, MYSQL -> {
                String resource = mysqlLockResource(namespace);
                String legacy = mysqlLockResourceLegacy(namespace);
                acquireMysqlLock(conn, dialect, resource);
                if (!legacy.equals(resource)) {
                    try {
                        acquireMysqlLock(conn, dialect, legacy);
                    } catch (RuntimeException | SQLException secondFailure) {
                        releaseMysqlLock(conn, resource);
                        throw secondFailure;
                    }
                    yield resource + ":" + legacy;
                }
                yield resource;
            }
            case SQLSERVER -> {
                String resource = "schema_synchronizer_" + namespace.toLowerCase(Locale.ROOT);
                try (var statement = conn.prepareStatement(
                        "DECLARE @result INT; "
                                + "EXEC @result = sp_getapplock @Resource = ?, @LockMode = 'Exclusive', "
                                + "@LockOwner = 'Session', @LockTimeout = 30000; "
                                + "SELECT @result")) {
                    statement.setString(1, resource);
                    try (var row = statement.executeQuery()) {
                        if (!row.next() || row.getInt(1) < 0) {
                            throw new IllegalStateException(
                                    "Could not acquire sqlserver schema synchronization lock");
                        }
                    }
                }
                yield resource;
            }
            case ORACLE -> {
                // release_on_commit=false: Oracle DDL implicitly commits; a transaction-
                // scoped lock would evaporate after the first CREATE/ALTER.
                // Acquire both 1.3.1 namespaced and 1.3.0 advisory-only lock ids so a
                // rolling upgrade still excludes peers on the prior hash.
                int lockId = Math.floorMod(Objects.hash("schema_synchronizer",
                        namespace.toLowerCase(Locale.ROOT), advisoryLockId), 1_073_741_823);
                int legacyLockId = Math.floorMod(Long.hashCode(advisoryLockId), 1_073_741_823);
                requestOracleLock(conn, lockId);
                if (legacyLockId != lockId) {
                    requestOracleLock(conn, legacyLockId);
                }
                yield Integer.toString(lockId) + ":" + legacyLockId;
            }
        };
    }

    static void releaseLock(Connection conn, DatabaseDialect dialect, String lockToken) throws SQLException {
        if (lockToken == null || lockToken.isBlank()) {
            return;
        }
        switch (dialect) {
            case MARIADB, MYSQL -> {
                for (String part : lockToken.split(":")) {
                    if (!part.isBlank()) {
                        releaseMysqlLock(conn, part);
                    }
                }
            }
            case SQLSERVER -> {
                try (var statement = conn.prepareStatement(
                        "DECLARE @result INT; "
                                + "EXEC @result = sp_releaseapplock @Resource = ?, @LockOwner = 'Session'; "
                                + "SELECT @result")) {
                    statement.setString(1, lockToken);
                    statement.executeQuery().close();
                }
            }
            case ORACLE -> {
                for (String part : lockToken.split(":")) {
                    if (part.isBlank()) {
                        continue;
                    }
                    int lockId = Integer.parseInt(part);
                    try (var statement = conn.prepareCall("{ ? = call DBMS_LOCK.RELEASE(?) }")) {
                        statement.registerOutParameter(1, Types.INTEGER);
                        statement.setInt(2, lockId);
                        statement.execute();
                        int status = statement.getInt(1);
                        // 0 = success, 3 = parameter error ignored when lock already gone, 4 = do not own
                        if (status != 0 && status != 3 && status != 4) {
                            throw new SQLException("Could not release oracle schema synchronization lock (status="
                                    + status + ")");
                        }
                    }
                }
            }
            case POSTGRESQL -> {
                // transaction-scoped advisory lock released on commit/rollback
            }
        }
    }

    /** Package-visible for contract tests. SHA-256 form used from 1.4.0. */
    static String mysqlLockResource(String namespace) {
        String full = "schema_synchronizer_" + namespace.toLowerCase(Locale.ROOT);
        if (full.length() <= MYSQL_LOCK_NAME_MAX) {
            return full;
        }
        // MySQL truncates GET_LOCK names at 64 chars — SHA-256 prefix avoids silent collisions.
        try {
            var digest = java.security.MessageDigest.getInstance("SHA-256");
            byte[] hash = digest.digest(full.getBytes(java.nio.charset.StandardCharsets.UTF_8));
            String hex = java.util.HexFormat.of().formatHex(hash);
            return ("ss_" + hex).substring(0, MYSQL_LOCK_NAME_MAX);
        } catch (java.security.NoSuchAlgorithmException exception) {
            throw new IllegalStateException("SHA-256 required for MySQL lock naming", exception);
        }
    }

    /** 1.3.1 hashCode form — dual-acquired with {@link #mysqlLockResource} during upgrades. */
    static String mysqlLockResourceLegacy(String namespace) {
        String full = "schema_synchronizer_" + namespace.toLowerCase(Locale.ROOT);
        if (full.length() <= MYSQL_LOCK_NAME_MAX) {
            return full;
        }
        return "ss_" + Integer.toHexString(full.hashCode());
    }

    /** Package-visible for contract tests. */
    static int namespaceLockKey(String namespace) {
        return Math.floorMod(("schema_synchronizer_" + namespace.toLowerCase(Locale.ROOT)).hashCode(),
                Integer.MAX_VALUE);
    }

    private static void acquireMysqlLock(Connection conn, DatabaseDialect dialect, String resource)
            throws SQLException {
        try (var statement = conn.prepareStatement("SELECT GET_LOCK(?, 30)")) {
            statement.setString(1, resource);
            try (var row = statement.executeQuery()) {
                if (!(row.next() && row.getInt(1) == 1)) {
                    throw new IllegalStateException("Could not acquire " + dialect.id()
                            + " schema synchronization lock");
                }
            }
        }
    }

    private static void releaseMysqlLock(Connection conn, String resource) throws SQLException {
        try (var statement = conn.prepareStatement("SELECT RELEASE_LOCK(?)")) {
            statement.setString(1, resource);
            statement.executeQuery().close();
        }
    }

    private static final long LOCK_WAIT_NANOS = java.util.concurrent.TimeUnit.SECONDS.toNanos(30);
    private static final long LOCK_POLL_MILLIS = 100L;

    private static void acquirePostgresLocks(Connection conn, int key1, int key2, long legacyKey)
            throws SQLException {
        long deadline = System.nanoTime() + LOCK_WAIT_NANOS;
        boolean primary = false;
        boolean legacy = false;
        try (Statement statement = conn.createStatement()) {
            while (!(primary && legacy)) {
                if (!primary) {
                    primary = tryPostgresLock(statement,
                            "SELECT pg_try_advisory_xact_lock(" + key1 + ", " + key2 + ")");
                }
                if (!legacy) {
                    legacy = tryPostgresLock(statement,
                            "SELECT pg_try_advisory_xact_lock(" + legacyKey + ")");
                }
                if (primary && legacy) {
                    return;
                }
                if (System.nanoTime() >= deadline) {
                    throw new IllegalStateException(
                            "Could not acquire postgresql schema synchronization lock within 30s");
                }
                try {
                    Thread.sleep(LOCK_POLL_MILLIS);
                } catch (InterruptedException interrupted) {
                    Thread.currentThread().interrupt();
                    throw new IllegalStateException(
                            "Interrupted while waiting for postgresql schema synchronization lock",
                            interrupted);
                }
            }
        }
    }

    private static boolean tryPostgresLock(Statement statement, String sql) throws SQLException {
        try (var row = statement.executeQuery(sql)) {
            return row.next() && row.getBoolean(1);
        }
    }

    private static void requestOracleLock(Connection conn, int lockId) throws SQLException {
        try (var statement = conn.prepareCall("{ ? = call DBMS_LOCK.REQUEST(?, 6, 30, false) }")) {
            statement.registerOutParameter(1, Types.INTEGER);
            statement.setInt(2, lockId);
            statement.execute();
            int status = statement.getInt(1);
            // 0 = success, 4 = already owned by this session
            if (status != 0 && status != 4) {
                throw new IllegalStateException(
                        "Could not acquire oracle schema synchronization lock (status=" + status + ")");
            }
        }
    }

    private static String escapeSqlServerLiteral(String value) {
        return value.replace("'", "''");
    }
}
